#!/usr/bin/env python3
"""
Terminal Discord Rich Presence Service
Lightweight, privacy-focused Discord RPC for Windows Terminal, PowerShell, and CMD.
"""

import json
import os
import sys
import time
import uuid
import struct
import tempfile
import socket
from pathlib import Path

# IPC Opcodes
OP_HANDSHAKE = 0
OP_FRAME = 1
OP_CLOSE = 2
OP_PING = 3
OP_PONG = 4

LOCK_PORT = 64321
_LOCK_SOCKET = None  # Global handle to prevent garbage collection releasing lock socket

def ensure_single_instance():
    """
    Ensures that only one instance of terminal_rpc.py runs at a time.
    Binds a local socket port as a mutex lock and retains the global reference.
    """
    global _LOCK_SOCKET
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind(("127.0.0.1", LOCK_PORT))
        s.listen(1)
        _LOCK_SOCKET = s
        return True
    except Exception:
        print("[Notice] Another instance of Terminal Discord Presence is already running. Exiting.")
        sys.exit(0)

def get_state_file_path():
    """Get cross-platform or Windows temp path for shell state sharing."""
    temp_dir = tempfile.gettempdir()
    return os.path.join(temp_dir, "discord_terminal_state.json")

def sanitize_path(path_str, privacy_mode="folder"):
    """
    Sanitizes file path based on privacy mode.
    Modes:
      - 'folder': returns only the current folder name (e.g. 'my-project')
      - 'full': replaces user home directory with '~' and uses forward slashes
      - 'hidden': returns fixed generic text
    """
    if not path_str or privacy_mode == "hidden":
        return "Workspace"

    path_str = path_str.replace("\\", "/")
    if path_str.endswith("/") and len(path_str) > 1 and not path_str.endswith(":/"):
        path_str = path_str.rstrip("/")

    path_obj = Path(path_str)

    if privacy_mode == "folder":
        folder_name = path_obj.name
        if not folder_name or folder_name.endswith(":"):
            return path_str
        return folder_name

    if privacy_mode == "full":
        home = str(Path.home()).replace("\\", "/")
        if path_str.startswith(home):
            path_str = "~" + path_str[len(home):]
        return path_str

    return path_obj.name or path_str

